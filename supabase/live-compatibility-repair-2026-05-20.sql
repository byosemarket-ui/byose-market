-- Byose Market - production-safe Supabase compatibility repair
-- Date: 2026-05-20
-- Goal: align the live Supabase project to the current codebase without enabling unsafe public writes.
-- Important: this script intentionally secures writes. Admin product creation/update/upload must move to a
-- backend service-role path or signed upload URL workflow after this migration.

begin;

create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

