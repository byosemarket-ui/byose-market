-- Remove known unsafe policies from the checked-in bootstrap.
drop policy if exists products_select_public on public.products;
drop policy if exists products_write_public on public.products;
drop policy if exists users_read_write_public on public.users;
drop policy if exists orders_read_write_public on public.orders;
drop policy if exists cart_items_read_write_public on public.cart_items;
drop policy if exists visits_read_write_public on public.visits;
drop policy if exists visitors_read_write_public on public.visitors;
drop policy if exists product_reviews_read_write_public on public.product_reviews;

-- Public storefront read only for active products.
create policy products_select_public
on public.products
for select
using (coalesce(status, 'active') in ('active', 'published'));

-- Optional public review reads if the product detail page needs them.
drop policy if exists product_reviews_select_public on public.product_reviews;
create policy product_reviews_select_public
on public.product_reviews
for select
using (coalesce(status, 'published') = 'published');

-- Do not create anon write policies for products, users, orders, cart_items, visits, visitors, or order_items.
-- Service-role backend operations bypass RLS and should handle admin/product/media writes safely.

-- -----------------------------------------------------------------------------
-- STORAGE
-- -----------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
select 'products', 'products', true
where not exists (
  select 1 from storage.buckets where id = 'products'
);

update storage.buckets
set public = true
where id = 'products';

drop policy if exists products_bucket_read_public on storage.objects;
drop policy if exists products_bucket_write_public on storage.objects;
drop policy if exists products_bucket_insert_public on storage.objects;
drop policy if exists products_bucket_update_public on storage.objects;
drop policy if exists products_bucket_delete_public on storage.objects;

create policy products_bucket_read_public
on storage.objects
for select
using (bucket_id = 'products');

